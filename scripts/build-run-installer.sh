#!/bin/sh
set -eu

if [ "$#" -ne 2 ]; then
    printf 'Usage: %s APK_DIR OUTPUT_FILE\n' "$0" >&2
    exit 2
fi

repo=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
apk_dir=$(CDPATH='' cd -- "$1" && pwd)
output=$2
core=xkeenwrt-core-0.1.26.3-r0.apk
ui=xkeenwrt-ui-0.1.26.3-r0.apk

(
    cd "$apk_dir"
    printf '%s  %s\n' \
        45f7f5f17b0f5acd811bf53ea1f371581b18de3b247d9e7d9cadc5a292e20e6d "$core" \
        64faf1b3db1d5adf525aaa32ed7bac8f15f6f9bd77d57a4ec2a202b6fe71c5f2 "$ui" |
        sha256sum -c -
)

work_dir=$(mktemp -d)
cleanup() {
    for file in "$work_dir/payload.tar" "$work_dir/installer.sh"; do
        [ ! -f "$file" ] || rm -- "$file"
    done
    rmdir -- "$work_dir"
}
trap cleanup EXIT
trap 'exit 1' HUP INT TERM

# The payload records root as owner, not the account that built it: GNU tar
# on Linux, bsdtar on macOS.
if tar --version 2>/dev/null | grep -q 'GNU tar'; then
    owner='--owner=0 --group=0 --numeric-owner'
else
    owner='--uid 0 --gid 0 --uname root --gname root'
fi
# shellcheck disable=SC2086 # $owner is a fixed list of flags
COPYFILE_DISABLE=1 tar --format ustar $owner -cf "$work_dir/payload.tar" -C "$repo" install.sh -C "$apk_dir" "$core" "$ui"
cat > "$work_dir/installer.sh" <<'HEADER'
#!/bin/sh
# XkeenWRT 0.1.26.3. Generated by scripts/build-run-installer.sh.
set -eu
umask 077
stage=$(mktemp -d /tmp/xkeenwrt-bundle.XXXXXX)
clean_stage() {
    for file in install.sh xkeenwrt-core-0.1.26.3-r0.apk xkeenwrt-ui-0.1.26.3-r0.apk; do
        [ ! -f "$stage/$file" ] || rm -- "$stage/$file"
    done
    rmdir -- "$stage"
}
trap clean_stage EXIT
trap 'exit 1' HUP INT TERM
start=$(awk '/^__XKEENWRT_ARCHIVE__$/ {print NR + 1; exit}' "$0")
[ -n "$start" ]
tail -n "+$start" "$0" | tar -xf - -C "$stage"
sh "$stage/install.sh" --from-dir "$stage"
exit
HEADER

sh -n "$work_dir/installer.sh"
printf '__XKEENWRT_ARCHIVE__\n' >> "$work_dir/installer.sh"
cat "$work_dir/payload.tar" >> "$work_dir/installer.sh"
mv -- "$work_dir/installer.sh" "$output"
